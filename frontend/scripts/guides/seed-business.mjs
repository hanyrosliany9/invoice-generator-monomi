  await api('PATCH', `/invoices/${paid.id}/status`, { status: 'SENT' });
  const pay2 = await api('POST', '/payments', { invoiceId: paid.id, amount: 5000000, paymentDate: isoDay(-1), paymentMethod: 'BANK_TRANSFER', transactionRef: 'TRF-DEMO-0043' });
